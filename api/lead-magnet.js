// ── Submission storage ───────────────────────────────────────────────────
// Same posture as api/assessment.js: persist BEFORE any provider is called,
// over plain fetch to PostgREST (no npm dependency, no package.json), and
// best effort, because the person is handed the PDF link regardless.

const SUPABASE_URL = (
  process.env.SUPABASE_URL ||
  process.env.NEXT_PUBLIC_SUPABASE_URL ||
  process.env.POSTGRES_SUPABASE_URL ||
  ''
).replace(/\/+$/, '');
const SERVICE_KEY =
  process.env.SUPABASE_SERVICE_ROLE_KEY ||
  process.env.SUPABASE_SERVICE_KEY ||
  process.env.POSTGRES_SUPABASE_SERVICE_ROLE_KEY;

const STORE_TABLE = 'lead_magnet_submissions';

function storageConfigured() {
  return Boolean(SUPABASE_URL && SERVICE_KEY);
}

async function sb(path, init = {}) {
  const r = await fetch(`${SUPABASE_URL}/rest/v1/${path}`, {
    ...init,
    headers: {
      apikey: SERVICE_KEY,
      Authorization: `Bearer ${SERVICE_KEY}`,
      'Content-Type': 'application/json',
      ...(init.headers || {}),
    },
  });
  if (!r.ok) {
    const detail = await r.text().catch(() => '');
    throw new Error(`Supabase ${r.status}: ${detail.slice(0, 200)}`);
  }
  return r;
}

async function storeSubmission(record) {
  if (!storageConfigured()) {
    console.warn('Supabase not configured; lead magnet submission not persisted');
    return null;
  }
  try {
    const r = await sb(STORE_TABLE, {
      method: 'POST',
      headers: { Prefer: 'return=representation' },
      body: JSON.stringify(record),
    });
    const rows = await r.json();
    return (Array.isArray(rows) ? rows[0] : rows)?.id ?? null;
  } catch (err) {
    console.error('Failed to persist lead magnet submission:', err?.message);
    return null;
  }
}

async function markSubmission(id, status, detail) {
  if (id == null || !storageConfigured()) return;
  try {
    await sb(`${STORE_TABLE}?id=eq.${encodeURIComponent(id)}`, {
      method: 'PATCH',
      body: JSON.stringify({
        status,
        detail: detail == null ? null : (typeof detail === 'string' ? detail : JSON.stringify(detail)),
      }),
    });
  } catch (err) {
    console.error('Failed to update lead magnet submission status:', err?.message);
  }
}

// ── Brevo ────────────────────────────────────────────────────────────────

async function brevo(key, path, init = {}) {
  const r = await fetch(`https://api.brevo.com/v3${path}`, {
    ...init,
    headers: {
      'Content-Type': 'application/json',
      Accept: 'application/json',
      'api-key': key,
      ...(init.headers || {}),
    },
  });
  const text = await r.text().catch(() => '');
  let data = null;
  try { data = text ? JSON.parse(text) : null; } catch { data = null; }
  if (!r.ok) {
    throw new Error(`Brevo ${r.status} ${path}: ${text.slice(0, 200)}`);
  }
  return data;
}

// Find or create the "Lead magnets" folder. Nothing is cached: a serverless
// instance has no durable memory and the extra two or three GETs per
// download are cheap next to being wrong about a deleted folder.
async function brevoFolderId(key) {
  const PAGE = 50;
  for (let offset = 0; offset < 1000; offset += PAGE) {
    const data = await brevo(key, `/contacts/folders?limit=${PAGE}&offset=${offset}`);
    const folders = Array.isArray(data?.folders) ? data.folders : [];
    const hit = folders.find(f => f && f.name === BREVO_FOLDER);
    if (hit) return hit.id;
    if (folders.length < PAGE) break;
  }
  const created = await brevo(key, '/contacts/folders', {
    method: 'POST',
    body: JSON.stringify({ name: BREVO_FOLDER }),
  });
  if (created?.id == null) throw new Error('Brevo folder create returned no id');
  return created.id;
}

async function brevoListId(key, listName) {
  const folderId = await brevoFolderId(key);
  const PAGE = 50;
  for (let offset = 0; offset < 2000; offset += PAGE) {
    const data = await brevo(key, `/contacts/lists?limit=${PAGE}&offset=${offset}`);
    const lists = Array.isArray(data?.lists) ? data.lists : [];
    const hit = lists.find(l => l && l.name === listName);
    if (hit) return hit.id;
    if (lists.length < PAGE) break;
  }
  const created = await brevo(key, '/contacts/lists', {
    method: 'POST',
    body: JSON.stringify({ name: listName, folderId }),
  });
  if (created?.id == null) throw new Error('Brevo list create returned no id');
  return created.id;
}

async function brevoUpsertContact(key, { email, firstName, agency, magnet }) {
  const listId = await brevoListId(key, MAGNETS[magnet].list);
  const body = {
    email,
    attributes: {
      FIRSTNAME: firstName,
      AGENCY: agency || '',
      LEAD_MAGNET: magnet,
    },
    listIds: [listId],
    updateEnabled: true,
  };
  // POST with updateEnabled creates or updates (Brevo answers 201 or 204).
  await brevo(key, '/contacts', { method: 'POST', body: JSON.stringify(body) });
  return listId;
}

// ── SMTP2GO ──────────────────────────────────────────────────────────────

async function smtpSend(smtpKey, message) {
  const r = await fetch('https://api.smtp2go.com/v3/email/send', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ api_key: smtpKey, ...message }),
  });
  // SMTP2GO returns HTTP 200 even when a send is refused, so inspect the body.
  const data = await r.json().catch(() => null);
  if (data?.data?.succeeded > 0) return { ok: true };
  return {
    ok: false,
    detail: {
      httpStatus: r.status,
      errorCode: data?.data?.error_code ?? data?.error_code ?? null,
      error: data?.data?.error ?? data?.error ?? null,
      failures: data?.data?.failures ?? null,
    },
  };
}

