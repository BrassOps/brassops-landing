export default async function handler(req, res) {
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed' });
  }

  // Origin check
  const origin = req.headers.origin || req.headers.referer || '';
  const isAllowedOrigin =
    ALLOWED_ORIGINS.some(a => origin.startsWith(a)) ||
    origin.startsWith('http://localhost');
  if (origin && !isAllowedOrigin) {
    return res.status(403).json({ error: 'Forbidden' });
  }

  // Body validation
  if (!req.body || typeof req.body !== 'object') {
    return res.status(400).json({ error: 'Invalid request body' });
  }

  const { magnet, first_name, email, agency, website } = req.body;

  // Honeypot: answer as if it worked, hand out nothing.
  if (website) {
    return res.status(200).json({ ok: true });
  }

  if (typeof magnet !== 'string' || !Object.prototype.hasOwnProperty.call(MAGNETS, magnet)) {
    return res.status(400).json({ error: 'Unknown download' });
  }

  if (!first_name || !email) {
    return res.status(400).json({ error: 'Missing required fields' });
  }
  if (typeof first_name !== 'string' || typeof email !== 'string') {
    return res.status(400).json({ error: 'Invalid field types' });
  }
  if (agency != null && typeof agency !== 'string') {
    return res.status(400).json({ error: 'Invalid field types' });
  }

  const firstName = first_name.trim();
  const safeEmail = email.trim();
  const safeAgency = (agency || '').trim();

  if (!firstName || !safeEmail) {
    return res.status(400).json({ error: 'Missing required fields' });
  }
  if (firstName.length > LIMITS.firstName || safeEmail.length > LIMITS.email || safeAgency.length > LIMITS.agency) {
    return res.status(400).json({ error: 'Input exceeds maximum length' });
  }
  if (!EMAIL_REGEX.test(safeEmail)) {
    return res.status(400).json({ error: 'Invalid email format' });
  }

  const m = MAGNETS[magnet];
  const pdfUrl = m.path;
  const result = { ok: true, url: pdfUrl };

  // Persist before any provider call, and before the API key checks, so a
  // misconfiguration still leaves the lead recoverable.
  const submissionId = await storeSubmission({
    status: 'pending',
    magnet,
    first_name: firstName,
    email: safeEmail,
    agency: safeAgency || null,
    ip: clientIp(req),
    user_agent: String(req.headers['user-agent'] || '').slice(0, 400) || null,
  });

  const smtpKey = process.env.SMTP2GO_API_KEY;
  const brevoKey = process.env.BREVO_API_KEY;
  const recipient = process.env.CONTACT_RECIPIENT || 'info@brassops.com';

  const problems = {};

  // ── Brevo: folder, list, contact ──
  if (brevoKey) {
    try {
      const listId = await brevoUpsertContact(brevoKey, { email: safeEmail, firstName, agency: safeAgency, magnet });
      result.listId = listId;
    } catch (err) {
      console.error('Brevo lead magnet sync failed:', err?.message);
      problems.brevo = err?.message ?? 'request failed';
    }
  } else {
    console.warn('BREVO_API_KEY not configured; lead magnet contact not synced');
    problems.brevo = 'BREVO_API_KEY not configured';
  }

  if (!smtpKey) {
    console.error('SMTP2GO_API_KEY not configured');
    problems.smtp = 'SMTP2GO_API_KEY not configured';
    await markSubmission(submissionId, 'failed', problems);
    return res.status(200).json(result);
  }

  const safeFirst = firstName.replace(/[\r\n]/g, '').slice(0, 50);
  const safeAgencySubject = (safeAgency || 'unknown agency').replace(/[\r\n]/g, '').slice(0, 80);

  // ── Download email to the person ──
  try {
    const sent = await smtpSend(smtpKey, {
      to: [safeEmail],
      sender: 'BrassOps <noreply@brassops.com>',
      subject: `Your BrassOps download: ${m.label}`,
      html_body: downloadEmailHtml({ firstName, magnet }),
      text_body: downloadEmailText({ firstName, magnet }),
    });
    if (!sent.ok) {
      console.error('SMTP2GO download email rejected', sent.detail);
      problems.downloadEmail = sent.detail;
    }
  } catch (err) {
    console.error('SMTP2GO download email failed:', err?.message);
    problems.downloadEmail = { error: err?.message ?? 'request failed' };
  }

  // ── Admin notification ──
  const adminHtmlBody = `
    <h2 style="color:#0a0a0a;font-family:sans-serif;">New Lead Magnet Download</h2>
    <table style="border-collapse:collapse;width:100%;max-width:600px;font-family:sans-serif;">
      <tr><td style="padding:8px 12px;font-weight:bold;color:#555;border-bottom:1px solid #eee;">Download</td><td style="padding:8px 12px;border-bottom:1px solid #eee;font-weight:700;">${escapeHtml(m.label)}</td></tr>
      <tr><td style="padding:8px 12px;font-weight:bold;color:#555;border-bottom:1px solid #eee;">Name</td><td style="padding:8px 12px;border-bottom:1px solid #eee;">${escapeHtml(firstName)}</td></tr>
      <tr><td style="padding:8px 12px;font-weight:bold;color:#555;border-bottom:1px solid #eee;">Email</td><td style="padding:8px 12px;border-bottom:1px solid #eee;"><a href="mailto:${escapeHtml(safeEmail)}">${escapeHtml(safeEmail)}</a></td></tr>
      <tr><td style="padding:8px 12px;font-weight:bold;color:#555;border-bottom:1px solid #eee;">Agency</td><td style="padding:8px 12px;border-bottom:1px solid #eee;">${escapeHtml(safeAgency || 'Not given')}</td></tr>
      <tr><td style="padding:8px 12px;font-weight:bold;color:#555;border-bottom:1px solid #eee;">Brevo list</td><td style="padding:8px 12px;border-bottom:1px solid #eee;">${escapeHtml(m.list)}${result.listId != null ? ` (#${result.listId})` : ' (sync failed)'}</td></tr>
    </table>
    <p style="margin-top:20px;font-family:sans-serif;font-size:13px;color:#888;">This lead requested a download from ${escapeHtml(SITE + m.page)}</p>
  `;
  const adminTextBody = [
    'NEW LEAD MAGNET DOWNLOAD',
    `Download: ${m.label}`,
    `Name: ${firstName}`,
    `Email: ${safeEmail}`,
    `Agency: ${safeAgency || 'Not given'}`,
    `Brevo list: ${m.list}${result.listId != null ? ` (#${result.listId})` : ' (sync failed)'}`,
    `Page: ${SITE}${m.page}`,
  ].join('\n');

  try {
    const sent = await smtpSend(smtpKey, {
      to: [recipient],
      sender: 'BrassOps Lead Magnet <noreply@brassops.com>',
      subject: `Lead Magnet: ${safeFirst} at ${safeAgencySubject} downloaded ${m.label}`,
      html_body: adminHtmlBody,
      text_body: adminTextBody,
    });
    if (!sent.ok) {
      console.error('SMTP2GO admin email rejected', sent.detail);
      problems.adminEmail = sent.detail;
    }
  } catch (err) {
    console.error('SMTP2GO admin email failed:', err?.message);
    problems.adminEmail = { error: err?.message ?? 'request failed' };
  }

  if (Object.keys(problems).length === 0) {
    await markSubmission(submissionId, 'sent');
  } else {
    // The download email reaching the person is what "sent" means here; a
    // Brevo or admin-notice failure is recorded but does not fail the row.
    await markSubmission(submissionId, problems.downloadEmail ? 'failed' : 'sent', problems);
  }

  // Always ok with the url: the person is never stuck behind a provider.
  return res.status(200).json(result);
}

function clientIp(req) {
  const fwd = req.headers['x-forwarded-for'];
  if (typeof fwd === 'string' && fwd.length) return fwd.split(',')[0].trim();
  return req.headers['x-real-ip'] || 'unknown';
}

function escapeHtml(str) {
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
